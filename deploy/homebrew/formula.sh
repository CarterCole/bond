#!/bin/sh
# Print the Homebrew formula for a release.
#
#   deploy/homebrew/formula.sh <version> <download url> <dir with the archives>
#
# The archives are the ones `make release` builds. The formula installs those
# prebuilt binaries, so installing needs no Go toolchain. BOND_REPO is the
# GitHub repository the formula links to (default CarterCole/bond).
set -eu

if [ $# -ne 3 ]; then
	sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'
	exit 2
fi
version=$1 url=$2 dir=$3
repo=${BOND_REPO:-CarterCole/bond}

sha() {
	f="$dir/bond-$version-$1.tar.gz"
	[ -f "$f" ] || { echo "missing $f" >&2; exit 1; }
	shasum -a 256 "$f" | cut -d' ' -f1
}
darwin_arm64=$(sha darwin-arm64)
darwin_amd64=$(sha darwin-amd64)
linux_arm64=$(sha linux-arm64)
linux_amd64=$(sha linux-amd64)

cat <<EOF
# Generated by deploy/homebrew/formula.sh for bond $version. Do not edit.
class Bond < Formula
  desc "Combine several internet connections into one for live streaming"
  homepage "https://github.com/$repo"
  version "$version"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "$url/bond-$version-darwin-arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$url/bond-$version-darwin-amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$url/bond-$version-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$url/bond-$version-linux-amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "bondd", "bond"
  end

  def caveats
    <<~EOS
      Bond needs an aggregator, a server with a public address, to bond to:
        https://github.com/$repo#quick-start

      With the join code the aggregator printed, bond this machine's
      connections (all of its traffic goes through the bond):
        sudo bondd hub --join 'bond://...'

      Keep it running in the background and across reboots:
        sudo bondd service install hub --join 'bond://...'

      Without sudo nothing is captured; point applications at the SOCKS5
      proxy on 127.0.0.1:1080 instead:
        bondd hub --userspace --join 'bond://...'

      Watch it with "bond status" or at http://127.0.0.1:7780

      After upgrading, restart the service so it runs the new version:
        sudo bondd service restart hub
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/bondd version")

    # A userspace aggregator needs no root: start one and ask it for its
    # join code through the status API, as an operator would.
    admin = "127.0.0.1:#{free_port}"
    pid = spawn bin/"bondd", "server", "--userspace", "--no-upnp",
                "--listen", "127.0.0.1:#{free_port}", "--public", "127.0.0.1",
                "--admin", admin, "--state", testpath/"state"
    begin
      code = nil
      20.times do
        sleep 0.5
        code = Utils.popen_read(bin/"bond", "--admin", admin, "code")
        break if code.include?("bond://")
      end
      assert_match "bond://", code
    ensure
      Process.kill "TERM", pid
      Process.wait pid
    end
  end
end
EOF
